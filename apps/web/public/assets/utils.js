export const TIMEZONE = 'America/Mexico_City';

export function canonicalDate(value) {
  if (typeof value === 'number') return new Date(value * 1000);
  // Canonical backend timestamps without an offset are stored as UTC.
  if (typeof value === 'string' && /\d[T ]\d/.test(value) && !/(?:Z|[+-]\d{2}:?\d{2})$/i.test(value)) value += 'Z';
  return new Date(value);
}

export function localDay(date = new Date(), timezone = TIMEZONE) {
  const parts = new Intl.DateTimeFormat('en-CA', {timeZone: timezone, year: 'numeric', month: '2-digit', day: '2-digit'}).formatToParts(date);
  const value = type => parts.find(part => part.type === type).value;
  return `${value('year')}-${value('month')}-${value('day')}`;
}

export function spaceBase(spaceId) {
  if (typeof spaceId !== 'string' || !/^[a-zA-Z0-9_-]{1,100}$/.test(spaceId)) throw new Error('El identificador del espacio no es válido.');
  return `/s/${spaceId}`;
}

// File links generated by the assistant must always stay within the current space.
export function documentLink(path, spaceId) {
  if (typeof path !== 'string' || !/^\/v1\/documents\/[a-zA-Z0-9_%.-]+\/(?:versions\/\d+\/)?download$/.test(path)) return null;
  const documentId = path.split('/')[3];
  try {
    const decoded = decodeURIComponent(documentId);
    if (decoded === '.' || decoded === '..' || /[\/\\\x00-\x1f]/.test(decoded)) return null;
  } catch { return null; }
  return `${spaceBase(spaceId)}${path}`;
}

export function splitSse(buffer) {
  const parts = buffer.replace(/\r\n/g, '\n').split('\n\n');
  const remainder = parts.pop();
  const events = [];
  for (const part of parts) {
    const payload = part.split('\n').filter(line => line.startsWith('data:')).map(line => line.slice(5).trimStart()).join('\n');
    if (!payload) continue;
    try { events.push(JSON.parse(payload)); } catch { throw new Error('La respuesta del chat no es válida. Vuelve a conectar para recuperar el turno.'); }
  }
  return {events, remainder};
}

export function formatBytes(bytes) {
  if (bytes === undefined || bytes === null) return 'Sin medición';
  if (bytes === 0) return '0 B';
  const units = ['B', 'KB', 'MB', 'GB', 'TB'];
  const index = Math.min(Math.floor(Math.log(Math.max(1, bytes)) / Math.log(1024)), units.length - 1);
  return `${new Intl.NumberFormat('es-MX', {maximumFractionDigits: index > 1 ? 1 : 0}).format(bytes / 1024 ** index)} ${units[index]}`;
}

export function errorMessage(payload, status) {
  if (typeof payload?.detail === 'string') return payload.detail;
  if (Array.isArray(payload?.detail)) return payload.detail.map(item => item.msg).join('. ');
  if (typeof payload?.message === 'string') return payload.message;
  const messages = {401: 'Tu sesión terminó. Vuelve a conectar tu espacio.', 403: 'Tu sesión no permite esta operación. Recarga la página e inténtalo de nuevo.', 404: 'No se encontró el recurso solicitado.', 409: 'El estado cambió. Actualiza la página para continuar.', 413: 'El archivo supera el tamaño permitido.', 429: 'Se alcanzó el límite de solicitudes. Inténtalo en unos momentos.', 502: 'El espacio no responde en este momento.', 503: 'El servicio no está disponible temporalmente.'};
  return messages[status] || 'No se pudo completar la operación. Inténtalo nuevamente.';
}
